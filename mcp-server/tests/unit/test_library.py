    again = parse_ficha(render_ficha(ficha))
    assert (again.title, again.edition, again.text, again.extra) == (ficha.title, "1997", False, ficha.extra)
    assert [n.label for n in again.notes] == ["p. 2", "p. 4", "p. 6-8"]


