def test_filing_copies_with_the_standard_name_and_writes_the_ficha(
    call: Caller, incoming: Path, library_root: Path
) -> None:
    source = make_pdf(incoming)
    before = (source.read_bytes(), source.stat().st_mtime_ns)

    text = file_doc(call, source, pages=[{"p": "2", "what": "tabla de medidas d x l"}])

    target = library_root / f"{DOC_ID}.pdf"
    assert target.read_bytes() == source.read_bytes()
    assert (source.read_bytes(), source.stat().st_mtime_ns) == before  # the original is never touched
    assert f"filed: {DOC_ID}" in text and str(target) in text
    assert "pages: 3 | text: yes" in text and "cite as «DIN 7979, 1997, p. N»" in text
    ficha = parse_ficha(target.with_name(target.stem + ".ficha.md").read_text(encoding="utf-8"))
    assert (ficha.title, ficha.standard, ficha.edition, ficha.author) == (
        "Pasadores cilíndricos con rosca interior",
        "DIN 7979",
        "1997",
        "DIN",
    )
    assert (ficha.pages, ficha.text, ficha.original) == (3, True, "original.pdf")
    assert ficha.sha256 == hashlib.sha256(source.read_bytes()).hexdigest()
    assert [(n.first, n.last, n.what) for n in ficha.notes] == [(2, 2, "tabla de medidas d x l")]
    assert (library_root / "topics.yaml").is_file()  # the starting list is copied on first use


