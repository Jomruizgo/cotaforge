def make_pdf(folder: Path, name: str = "original.pdf", pages: list[str] | None = None) -> Path:
    path = folder / name
    path.write_bytes(pdf_bytes(PAGES if pages is None else pages))
    return path


def file_doc(call: Caller, path: Path, **extra: Any) -> str:
    return call.ok("catalog", action="file", entry={"path": str(path), **ENTRY, **extra})


