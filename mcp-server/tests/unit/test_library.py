def test_a_hand_edited_ficha_is_read_with_tolerance() -> None:
    ficha = parse_ficha(
        "---\ntitle: Pasadores\nedition: 1997\nfiled: 2026-10-31\ntext: false\nunknown_key: 1\n---\n"
        "Una nota libre del ingeniero.\n- p. 4: tabla\n* pp. 6–8: anexos\n- p. 2: alcance\n"
    )

    assert (ficha.edition, ficha.filed, ficha.text) == ("1997", "2026-10-31", False)
    assert [(n.first, n.last, n.what) for n in ficha.notes] == [(2, 2, "alcance"), (4, 4, "tabla"), (6, 8, "anexos")]
