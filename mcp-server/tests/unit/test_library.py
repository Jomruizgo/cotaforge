def test_an_update_extends_the_page_map_and_moves_the_document_with_its_ficha(
    call: Caller, incoming: Path, library_root: Path
) -> None:
    file_doc(call, make_pdf(incoming), pages=[{"p": "2", "what": "tabla vieja"}])

    text = call.ok(
        "catalog",
        action="file",
        entry={
            "id": DOC_ID,
            "topic": "roscas",
            "pages": [
                {"p": "2", "what": "tabla de medidas"},
                {"p": "1-1", "what": "alcance"},
                {"p": 3, "what": "anexo"},
            ],
        },
    )

    new_id = "roscas/" + Path(DOC_ID).name
    assert f"updated: {new_id}" in text and f"moved from {DOC_ID}" in text
    assert not (library_root / f"{DOC_ID}.pdf").exists() and not (library_root / f"{DOC_ID}.ficha.md").exists()
    ficha = parse_ficha((library_root / f"{new_id}.ficha.md").read_text(encoding="utf-8"))
    assert [(n.first, n.last, n.what) for n in ficha.notes] == [
        (1, 1, "alcance"),
        (2, 2, "tabla de medidas"),  # the same range replaced the old text
        (3, 3, "anexo"),
    ]
    assert ficha.sha256 and ficha.filed  # the rest of the ficha is kept

    removed = call.ok("catalog", action="file", entry={"id": new_id, "pages": [{"p": "3", "what": ""}]})
    assert "2 line(s)" in removed


