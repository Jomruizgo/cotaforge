def test_without_pypdf_the_fichas_still_work_and_the_reply_says_so(
    call: Caller, incoming: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(extract, "load_pypdf", lambda: None)

    text = file_doc(call, make_pdf(incoming), pages=[{"p": "2", "what": "tabla de medidas d x l"}])
