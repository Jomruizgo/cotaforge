"""Memory index rendering.

Two forms, both of active entries only ("inactive" means the entry exists but is neither enforced nor suggested):

* ``render_index``: the ``INDEX.md`` of one scope, one detailed line per entry (title, type, when it applies);
* ``combined_index``: what the agent reads (``memory(action=index)`` and the server instructions). It is compact,
  because an entry id is already a descriptive slug: ids grouped by scope and type (and by sector for the practices),
  wrapped at a sensible width, with the status that matters (proposed, replaced) next to the id. The title and when
  an entry applies are one ``memory(action=search)`` away.
"""

from collections.abc import Iterable
from dataclasses import dataclass

from cotaforge.memory.model import EntryStatus, EntryType, MemoryEntry, Scope, StoredEntry
from cotaforge.memory.sectors import LITERAL_PREFIX, SectorTable

INDEX_FILENAME = "INDEX.md"
MAX_LINE_LENGTH = 150
WRAP_WIDTH = 112
ELLIPSIS = "…"
INDEX_HEADER = "# Memory index (generated by cotaforge; do not edit by hand)"
INDEX_HINT = (
    "(ids only: memory(action=get, id) reads one; memory(action=search, text) shows titles and when each applies)"
)
NOT_DECLARED_HINT = (
    "(sector not declared: ask the engineer once and declare it with memory(action=brief, sector=...) "
    "to list its practices here; memory(action=index, sector=<id>) lists one sector's practices)"
)
SCOPE_LABEL = {Scope.project: "project", Scope.user: "user memory", Scope.base: "base"}
TYPE_ORDER = (
    EntryType.principle,
    EntryType.practice,
    EntryType.process,
    EntryType.material,
    EntryType.correction,
    EntryType.cad_trap,
    EntryType.case,
)
TYPE_LABEL = {
    EntryType.principle: "principles",
    EntryType.practice: "practices",
    EntryType.process: "processes",
    EntryType.material: "materials",
    EntryType.correction: "corrections",
    EntryType.cad_trap: "CAD traps",
    EntryType.case: "cases",
}


def _one_line(text: str) -> str:
    return " ".join(text.split())


def index_line(entry: MemoryEntry, replaced_by: str | None = None) -> str:
    """``- [title](id.md) · type · applies_when``, at most ``MAX_LINE_LENGTH`` characters. A base entry that an
    engineer entry replaces says so instead of when it applies."""
    title = _one_line(entry.title).replace("[", "(").replace("]", ")")
    if replaced_by:  # the marker is the point of the line: a long title gives way, not the marker
        rest = f"]({entry.id}.md) · {entry.type.value} · replaced by {replaced_by}"
        room = MAX_LINE_LENGTH - len("- [") - len(rest)
        if len(title) > room:
            title = title[: max(room - len(ELLIPSIS), 1)].rstrip() + ELLIPSIS
        return f"- [{title}{rest}"
    fixed = f"]({entry.id}.md) · {entry.type.value}"
    room = MAX_LINE_LENGTH - len("- [") - len(fixed)
    if len(title) > room:  # the id is what `memory get` needs: a long title gives way, never the id
        title = title[: max(room - len(ELLIPSIS), 1)].rstrip() + ELLIPSIS
        return f"- [{title}{fixed}"
    line = f"- [{title}{fixed} · {_one_line(entry.applies_when)}"
    if len(line) > MAX_LINE_LENGTH:
        line = line[: MAX_LINE_LENGTH - len(ELLIPSIS)].rstrip() + ELLIPSIS
    return line


def _sorted_active(entries: Iterable[MemoryEntry]) -> list[MemoryEntry]:
    return sorted((entry for entry in entries if entry.is_active), key=lambda entry: (entry.type.value, entry.id))


def _sorted_proposed(entries: Iterable[MemoryEntry]) -> list[MemoryEntry]:
    return sorted((entry for entry in entries if entry.is_proposed), key=lambda entry: (entry.type.value, entry.id))


PENDING_HEADING = "pending approval (proposed by the agent: not rules until the engineer approves them)"


def render_index(entries: Iterable[MemoryEntry]) -> str:
    """The text of one scope's ``INDEX.md``: header, then active entries sorted by type then id."""
    lines = [INDEX_HEADER, ""]
    stored = list(entries)
    lines.extend(index_line(entry) for entry in _sorted_active(stored))
    pending = _sorted_proposed(stored)
    if pending:
        lines.extend(["", f"## {PENDING_HEADING}", ""])
        lines.extend(index_line(entry) for entry in pending)
    return "\n".join(lines) + "\n"


# ---- the compact index -------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class SectorView:
    """How the index presents the practices of the base set: a base practice is listed only when its sector is in
    ``listed`` (the project's sector, or the one asked for); the others collapse to one line per sector.
    ``declared`` says whether the project declared a sector (it adds a hint to declare it when not)."""

    table: SectorTable
    listed: frozenset[str] = frozenset()
    declared: bool = False


@dataclass(frozen=True)
class IndexGroup:
    """Entries of one scope and type (and sector, for practices): ``label`` and the ids with their markers."""

    label: str
    ids: tuple[str, ...]


def _collapsed_line(sector: str, count: int) -> str:
    noun = "práctica" if count == 1 else "practices"
    return f"- {sector}: {count} {noun} (memory index sector={sector})"


def _marked(entry: MemoryEntry, replaced_by: str | None) -> str:
    if replaced_by:
        return f"{entry.id} [replaced by {replaced_by}]"
    return f"{entry.id} [proposed]" if entry.status is EntryStatus.proposed else entry.id


def _sector_key(entry: MemoryEntry) -> str:
    return entry.sector or "" if entry.type is EntryType.practice else ""


def index_groups(entries: Iterable[StoredEntry], view: SectorView | None = None) -> tuple[list[IndexGroup], list[str]]:
    """``(groups, extra lines)``: the entries by scope (project, user, base), type and, for practices, sector; the extra
    lines are the collapsed sectors of the base set and the hint to declare the sector. An id that exists in both scopes
    appears once (the project one); inactive entries are left out. With a ``view`` the practices of the base set whose
    sector is not listed collapse to one line per sector (a replaced practice keeps its place: it says by which
    entry)."""
    stored = list(entries)
    effective = {item.entry.id: item for item in stored}
    replaced_by = {  # base id -> the active entry of the user or the project that replaces it
        item.entry.replaces: item.entry.id
        for item in sorted(stored, key=lambda row: row.entry.id)
        if item.scope is not Scope.base
        and item.entry.is_active
        and item.entry.replaces
        and item.entry.replaces in effective
        and effective[item.entry.replaces].scope is Scope.base
    }
    groups: list[IndexGroup] = []
    collapsed: dict[str, int] = {}
    for scope in (Scope.project, Scope.user, Scope.base):
        mine = [item.entry for item in stored if item.scope is scope and item.entry.status is not EntryStatus.inactive]
        mine.sort(key=lambda e: (TYPE_ORDER.index(e.type), _sector_key(e), e.id))
        pending: dict[tuple[EntryType, str], list[str]] = {}
        for entry in mine:
            replaced = replaced_by.get(entry.id) if scope is Scope.base else None
            sector = _sector_key(entry)
            if scope is Scope.base and view is not None and replaced is None and sector:
                keys = view.table.resolve(sector).keys()
                if not keys & view.listed:
                    label = sorted(keys)[0].removeprefix(LITERAL_PREFIX) if keys else sector
                    collapsed[label] = collapsed.get(label, 0) + 1
                    continue
            pending.setdefault((entry.type, sector), []).append(_marked(entry, replaced))
        for (kind, sector), ids in pending.items():
            suffix = f" {sector}" if sector else ""
            groups.append(IndexGroup(f"{SCOPE_LABEL[scope]} — {TYPE_LABEL[kind]}{suffix}", tuple(ids)))
    extra = [_collapsed_line(sector, count) for sector, count in sorted(collapsed.items())]
    if view is not None and collapsed and not view.declared:
        extra.append(NOT_DECLARED_HINT)
    return groups, extra


def render_group(group: IndexGroup, width: int = WRAP_WIDTH) -> list[str]:
    """``label: id, id, ...`` wrapped at ``width``; the continuation lines are indented by two spaces."""
    lines: list[str] = []
    current = f"{group.label}:"
    for position, entry_id in enumerate(group.ids):
        token = entry_id + ("," if position < len(group.ids) - 1 else "")
        if len(current) + 1 + len(token) > width and current.strip() and not current.endswith(":"):
            lines.append(current)
            current = "  " + token
        else:
            current += " " + token
    lines.append(current)
    return lines


def combined_index(entries: Iterable[StoredEntry], view: SectorView | None = None) -> str:
    """What the agent reads: both scopes and the base set in compact groups (see the module doc), project first.
    Without a ``view`` every base practice is listed; with one the practices of other sectors collapse
    (see ``SectorView``). Principles and every entry of the engineer are always listed."""
    groups, extra = index_groups(entries, view)
    lines = [INDEX_HEADER, INDEX_HINT]
    for group in groups:
        lines.extend(render_group(group))
    lines.extend(extra)
    return "\n".join(lines) + "\n"
